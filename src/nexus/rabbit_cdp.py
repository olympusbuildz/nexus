"""A minimal Chrome DevTools Protocol client for one page on https://os3.rabbit.tech.

Rabbit OS3 keeps its provider config server-side, behind same-origin web endpoints that
need the signed-in browser session. This module drives a real, headed Chrome that the
user signed into OS3 once, on a dedicated profile, and calls those endpoints with
``fetch()`` from inside the page. It never reads cookies or tokens out of the browser:
the bearer token is fetched and used inside the page and never returned.

Hard limits, each covered by a test:

* CDP is only ever reached on ``127.0.0.1``. Any other host, and any debugger URL that
  names another host or port, is refused.
* Chrome is launched headed, with the dedicated profile, and never with a spoofed user
  agent. CloudFront blocks headless Chrome; that is a block to report, not to bypass.
* One new target is opened and only that target is used. Other tabs are not listed to
  the caller, attached to, or closed. The target is closed when done.
* Nothing is evaluated unless the target's origin is exactly ``https://os3.rabbit.tech``.
  The check is made from outside the page and repeated inside every expression.
* A key goes into the page only for the register call, is deleted from ``window`` before
  the first await, and is scrubbed from anything this module returns or raises.

Whenever a limit stops the automatic path, :class:`ManualRequired` carries a reason code
and the caller falls back to telling the user what to paste.
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import logging
import re
import shutil
import subprocess
import sys
from collections.abc import AsyncIterator, Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol
from urllib.parse import quote, urlsplit

import httpx

logger = logging.getLogger("nexus")

ORIGIN = "https://os3.rabbit.tech"
SETTINGS_URL = f"{ORIGIN}/settings/api-keys"
LOOPBACK = "127.0.0.1"

HTTP_TIMEOUT = 5.0
EVAL_TIMEOUT = 30.0
LAUNCH_WAIT = 20.0
READY_WAIT = 25.0
POLL_INTERVAL = 0.25

_BLOCKED_PAGE = re.compile(r"403 ERROR|request blocked|generated by cloudfront", re.IGNORECASE)
_MAC_CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
_CHROME_NAMES = ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser")


class ManualRequired(Exception):
    """The automatic path cannot continue. ``code`` is stable; ``message`` is for a person."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


class PageError(Exception):
    """The page or the DevTools connection failed after a page was attached."""


@dataclass(frozen=True)
class ApiResponse:
    status: int
    data: Any = None

    @property
    def ok(self) -> bool:
        return 200 <= self.status < 300


class Connection(Protocol):
    async def send(self, message: str) -> None: ...

    async def recv(self) -> str: ...


Connect = Callable[[str], contextlib.AbstractAsyncContextManager[Connection]]
Spawn = Callable[[list[str]], Any]


def require_loopback(host: str) -> None:
    if host != LOOPBACK:
        raise ManualRequired(
            "cdp_not_loopback",
            f"Chrome DevTools is only ever used on {LOOPBACK}; refusing host {host!r}.",
        )


def require_loopback_url(url: str, port: int) -> None:
    """The debugger URL Chrome reports must name this host and port, nothing else."""
    parts = urlsplit(url)
    try:
        url_port = parts.port
    except ValueError:
        url_port = None
    if parts.scheme not in {"http", "ws"} or parts.hostname != LOOPBACK or url_port != port:
        raise ManualRequired(
            "cdp_not_loopback",
            f"Chrome reported a DevTools address other than {LOOPBACK}:{port}; refusing it.",
        )


def origin_of(url: str) -> str:
    parts = urlsplit(url)
    return f"{parts.scheme}://{parts.netloc}" if parts.scheme and parts.netloc else ""


def chrome_binary(explicit: str | None = None) -> str | None:
    if explicit:
        return explicit if Path(explicit).is_file() else shutil.which(explicit)
    if sys.platform == "darwin" and Path(_MAC_CHROME).is_file():
        return _MAC_CHROME
    for name in _CHROME_NAMES:
        found = shutil.which(name)
        if found:
            return found
    return None


def launch_argv(binary: str, *, port: int, profile: Path) -> list[str]:
    """Headed on purpose: there is no headless flag anywhere in this file."""
    return [
        binary,
        f"--remote-debugging-port={port}",
        f"--remote-debugging-address={LOOPBACK}",
        f"--user-data-dir={profile}",
        "--no-first-run",
        "--no-default-browser-check",
    ]


def _spawn(argv: list[str]) -> Any:
    return subprocess.Popen(
        argv,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )


def _default_connect(url: str) -> contextlib.AbstractAsyncContextManager[Connection]:
    try:
        import websockets
    except ImportError as exc:
        raise ManualRequired(
            "websocket_missing",
            "The websockets package is not installed, so Chrome cannot be driven.",
        ) from exc
    return websockets.connect(  # type: ignore[return-value]
        url, max_size=8 * 1024 * 1024, open_timeout=HTTP_TIMEOUT, ping_interval=None
    )


def _call_script(path: str, body: dict[str, Any], *, key_from_window: bool) -> str:
    """One self-contained page expression: origin guard, token, then the POST.

    The token never leaves the page. When ``key_from_window`` is set the key is read from
    ``window.__nexusKey`` and deleted before the first await.
    """
    key_line = "const key = window.__nexusKey; delete window.__nexusKey;" if key_from_window else ""
    payload = "{...body, key}" if key_from_window else "body"
    return f"""(async () => {{
  if (location.origin !== {json.dumps(ORIGIN)}) return {{guard: location.origin}};
  {key_line}
  const body = {json.dumps(body)};
  const tr = await fetch('/api/auth/token', {{credentials: 'include'}});
  if (!tr.ok) return {{auth_status: tr.status}};
  let tj = null;
  try {{ tj = await tr.json(); }} catch (e) {{ tj = null; }}
  const token = tj && (tj.token || tj.accessToken || tj.access_token);
  if (!token) return {{auth_status: 200, no_token: true}};
  const r = await fetch({json.dumps(path)}, {{
    method: 'POST',
    credentials: 'include',
    headers: {{'Content-Type': 'application/json', Authorization: 'Bearer ' + token}},
    body: JSON.stringify({payload}),
  }});
  let data = null;
  let json = true;
  try {{ data = await r.json(); }} catch (e) {{ json = false; }}
  return {{status: r.status, data, json}};
}})()"""


_SET_KEY = (
    f"(location.origin === {json.dumps(ORIGIN)}) ? (window.__nexusKey = {{key}}, true) : false"
)
_CLEAR_KEY = (
    f"(location.origin === {json.dumps(ORIGIN)}) ? (delete window.__nexusKey, true) : false"
)
_READY = f"(location.origin === {json.dumps(ORIGIN)}) ? document.readyState : 'wrong-origin'"
_PAGE_TEXT = (
    f"(location.origin === {json.dumps(ORIGIN)}) "
    "? ((document.title || '') + ' ' + ((document.body && document.body.innerText) || '')"
    ".slice(0, 400)) : ''"
)


class CdpPage:
    """The one os3.rabbit.tech page this module opened."""

    def __init__(
        self,
        conn: Connection,
        *,
        target_origin: Callable[[], Any],
        scrub: Callable[[str], str] = lambda text: text,
    ) -> None:
        self._conn = conn
        self._target_origin = target_origin
        self._scrub = scrub
        self._next_id = 0

    async def _evaluate(self, expression: str) -> Any:
        self._next_id += 1
        ident = self._next_id
        message = {
            "id": ident,
            "method": "Runtime.evaluate",
            "params": {
                "expression": expression,
                "awaitPromise": True,
                "returnByValue": True,
                "userGesture": False,
            },
        }

        async def exchange() -> Any:
            await self._conn.send(json.dumps(message))
            while True:
                reply = json.loads(await self._conn.recv())
                if reply.get("id") == ident:
                    return reply

        try:
            reply = await asyncio.wait_for(exchange(), timeout=EVAL_TIMEOUT)
        except TimeoutError as exc:
            raise PageError("The page did not answer in time.") from exc
        except Exception as exc:
            raise PageError(f"The DevTools connection failed: {type(exc).__name__}.") from exc
        if "error" in reply:
            raise PageError(self._scrub(str(reply["error"].get("message", "DevTools error"))))
        result = reply.get("result", {})
        if "exceptionDetails" in result:
            text = result["exceptionDetails"].get("text", "page exception")
            raise PageError(self._scrub(str(text)))
        return result.get("result", {}).get("value")

    async def _require_origin(self) -> None:
        origin = await self._target_origin()
        if origin != ORIGIN:
            raise ManualRequired(
                "wrong_origin",
                f"The OS3 tab is on {origin or 'an unknown page'}, not {ORIGIN}; nothing was run.",
            )

    async def wait_ready(self, *, deadline: float = READY_WAIT) -> None:
        """Wait for the tab to finish loading os3.rabbit.tech, and refuse a blocked page."""
        loop = asyncio.get_running_loop()
        end = loop.time() + deadline
        while True:
            origin = await self._target_origin()
            if origin == ORIGIN:
                state = await self._evaluate(_READY)
                if state == "complete":
                    break
            elif origin.startswith("chrome-error:"):
                raise ManualRequired("page_failed", "Chrome could not load os3.rabbit.tech.")
            elif origin not in {"", "about:", "null"} and not origin.startswith("about:"):
                raise ManualRequired(
                    "signed_out",
                    f"The OS3 tab was sent to {origin}, so this Chrome profile is not signed "
                    "in to OS3.",
                )
            if loop.time() >= end:
                raise ManualRequired("page_timeout", "os3.rabbit.tech did not finish loading.")
            await asyncio.sleep(POLL_INTERVAL)
        text = await self._evaluate(_PAGE_TEXT)
        if isinstance(text, str) and _BLOCKED_PAGE.search(text):
            raise ManualRequired(
                "blocked",
                "os3.rabbit.tech answered with a CloudFront block page. This is not worked around.",
            )

    def _interpret(self, value: Any) -> ApiResponse:
        if not isinstance(value, dict):
            raise PageError("The page returned an unexpected answer.")
        if "guard" in value:
            raise ManualRequired(
                "wrong_origin",
                f"The OS3 tab moved to {value['guard']!r}; the call was not made.",
            )
        if "auth_status" in value:
            status = value["auth_status"]
            if status == 403:
                raise ManualRequired(
                    "blocked", "os3.rabbit.tech refused the session check (403, CloudFront)."
                )
            raise ManualRequired(
                "signed_out",
                "No OS3 session token: this Chrome profile is not signed in to os3.rabbit.tech.",
            )
        status = value.get("status")
        if not isinstance(status, int):
            raise PageError("The page returned no HTTP status.")
        if status == 403 and not value.get("json"):
            raise ManualRequired(
                "blocked", "os3.rabbit.tech answered 403 with a non-JSON page (CloudFront)."
            )
        return ApiResponse(status, value.get("data"))

    async def call(self, path: str, body: dict[str, Any]) -> ApiResponse:
        await self._require_origin()
        return self._interpret(
            await self._evaluate(_call_script(path, body, key_from_window=False))
        )

    async def register(self, body: dict[str, Any], key: str) -> ApiResponse:
        """POST /api/byok/register with ``key`` placed in the page for this call only."""
        await self._require_origin()
        placed = await self._evaluate(_SET_KEY.format(key=json.dumps(key)))
        if placed is not True:
            raise ManualRequired("wrong_origin", "The OS3 tab moved; the key was not sent.")
        try:
            return self._interpret(
                await self._evaluate(_call_script("/api/byok/register", body, key_from_window=True))
            )
        finally:
            await self.clear_key()

    async def clear_key(self) -> None:
        with contextlib.suppress(Exception):
            await self._evaluate(_CLEAR_KEY)


class ChromeCdp:
    """Attach to, or launch, the dedicated Chrome and open one OS3 settings page."""

    def __init__(
        self,
        *,
        port: int,
        profile_dir: Path,
        host: str = LOOPBACK,
        chrome_bin: str | None = None,
        transport: httpx.AsyncBaseTransport | None = None,
        connect: Connect | None = None,
        spawn: Spawn | None = None,
        launch_wait: float = LAUNCH_WAIT,
        scrub: Callable[[str], str] = lambda text: text,
    ) -> None:
        self.host = host
        self.port = port
        self.profile_dir = profile_dir
        self._chrome_bin = chrome_bin
        self._transport = transport
        self._connect = connect or _default_connect
        self._spawn = spawn or _spawn
        self._launch_wait = launch_wait
        self._scrub = scrub

    def describe(self) -> dict[str, Any]:
        return {
            "host": self.host,
            "port": self.port,
            "profile_dir": str(self.profile_dir),
            "profile_exists": self.profile_dir.is_dir(),
            "chrome_found": chrome_binary(self._chrome_bin) is not None,
        }

    def _client(self) -> httpx.AsyncClient:
        return httpx.AsyncClient(
            base_url=f"http://{LOOPBACK}:{self.port}",
            timeout=HTTP_TIMEOUT,
            transport=self._transport,
            trust_env=False,
        )

    async def _version(self) -> dict[str, Any] | None:
        try:
            async with self._client() as client:
                reply = await client.get("/json/version")
        except (httpx.HTTPError, OSError):
            return None
        if reply.status_code != 200:
            return None
        try:
            body = reply.json()
        except ValueError:
            return None
        return body if isinstance(body, dict) else None

    async def listening(self) -> bool:
        require_loopback(self.host)
        return await self._version() is not None

    async def _launch(self) -> None:
        binary = chrome_binary(self._chrome_bin)
        if binary is None:
            raise ManualRequired(
                "chrome_unavailable",
                "Google Chrome was not found. Install it, or set NEXUS_RABBIT_CHROME_BIN.",
            )
        self.profile_dir.mkdir(parents=True, exist_ok=True)
        argv = launch_argv(binary, port=self.port, profile=self.profile_dir)
        try:
            self._spawn(argv)
        except OSError as exc:
            raise ManualRequired(
                "chrome_unavailable", f"Chrome could not be started: {exc.strerror or 'error'}."
            ) from exc
        loop = asyncio.get_running_loop()
        end = loop.time() + self._launch_wait
        while loop.time() < end:
            if await self._version() is not None:
                return
            await asyncio.sleep(POLL_INTERVAL)
        raise ManualRequired(
            "cdp_unavailable",
            f"Chrome started but nothing answered on {LOOPBACK}:{self.port}. If this profile "
            "is already open in a normal Chrome window, quit that window and retry.",
        )

    async def _open_target(self) -> dict[str, Any]:
        url = f"/json/new?{quote(SETTINGS_URL, safe=':/')}"
        try:
            async with self._client() as client:
                reply = await client.put(url)
                if reply.status_code == 405:
                    reply = await client.get(url)
        except (httpx.HTTPError, OSError) as exc:
            raise ManualRequired("cdp_unavailable", "Chrome did not open a new tab.") from exc
        try:
            target = reply.json()
        except ValueError:
            target = None
        if reply.status_code != 200 or not isinstance(target, dict):
            raise ManualRequired("cdp_unavailable", "Chrome did not open a new tab.")
        if not isinstance(target.get("id"), str) or not isinstance(
            target.get("webSocketDebuggerUrl"), str
        ):
            raise ManualRequired("cdp_unavailable", "Chrome gave no DevTools address for the tab.")
        return target

    async def _target_origin(self, target_id: str) -> str:
        """The origin of our own target, read from the target list and not from the page."""
        try:
            async with self._client() as client:
                reply = await client.get("/json/list")
            rows = reply.json()
        except (httpx.HTTPError, OSError, ValueError) as exc:
            raise PageError("Chrome's target list could not be read.") from exc
        for row in rows if isinstance(rows, list) else []:
            if isinstance(row, dict) and row.get("id") == target_id:
                url = str(row.get("url") or "")
                if not url:
                    return ""
                return origin_of(url) or url.split(":", 1)[0] + ":"
        raise PageError("The OS3 tab is gone.")

    async def _close_target(self, target_id: str) -> None:
        try:
            async with self._client() as client:
                await client.get(f"/json/close/{quote(target_id, safe='')}")
        except (httpx.HTTPError, OSError):
            logger.warning("rabbit: could not close the OS3 tab")

    @contextlib.asynccontextmanager
    async def open_page(self) -> AsyncIterator[CdpPage]:
        require_loopback(self.host)
        if await self._version() is None:
            await self._launch()
        target = await self._open_target()
        target_id = str(target["id"])
        try:
            ws_url = str(target["webSocketDebuggerUrl"])
            require_loopback_url(ws_url, self.port)
            if not urlsplit(ws_url).path.endswith(f"/{target_id}"):
                raise ManualRequired(
                    "cdp_unavailable", "Chrome's DevTools address is not for the tab we opened."
                )
            async with contextlib.AsyncExitStack() as stack:
                try:
                    conn = await stack.enter_async_context(self._connect(ws_url))
                except ManualRequired:
                    raise
                except Exception as exc:
                    raise ManualRequired(
                        "cdp_unavailable", f"DevTools could not be attached: {type(exc).__name__}."
                    ) from exc
                page = CdpPage(
                    conn,
                    target_origin=lambda: self._target_origin(target_id),
                    scrub=self._scrub,
                )
                try:
                    await page.wait_ready()
                except PageError as exc:
                    raise ManualRequired("page_failed", str(exc)) from exc
                try:
                    yield page
                finally:
                    await page.clear_key()
        finally:
            await self._close_target(target_id)
